"""Artifact writers: CSV, booktabs TeX and matplotlib PNG under eval/artifacts/<exp>/.

TeX tables are bare ``tabular`` fragments meant for ``\\input``; captions live
in the paper. PNGs use a plain matplotlib style (no seaborn dependency) and
are skipped gracefully when matplotlib is unavailable.
"""
from __future__ import annotations

import csv
import json
from pathlib import Path
from typing import Any, Sequence

from eval._bootstrap import REPO_ROOT

import os

ARTIFACTS = Path(os.environ.get("SUPERBROWSER_EVAL_ARTIFACTS_DIR") or (REPO_ROOT / "eval" / "artifacts"))


def set_artifacts_root(path: Path) -> None:
    """Redirect artifact output (tests, scratch analyses)."""
    global ARTIFACTS
    ARTIFACTS = Path(path)


def out_dir(experiment: str) -> Path:
    d = ARTIFACTS / experiment
    d.mkdir(parents=True, exist_ok=True)
    return d


def write_csv(path: Path, rows: Sequence[dict[str, Any]], *, columns: Sequence[str] | None = None) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        path.write_text("")
        return path
    cols = list(columns) if columns else list({k: None for r in rows for k in r}.keys())
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        for r in rows:
            w.writerow({k: _cell(r.get(k)) for k in cols})
    return path


def write_json(path: Path, obj: Any) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2, default=str, ensure_ascii=False) + "\n")
    return path


def _cell(v: Any) -> Any:
    if isinstance(v, float):
        return f"{v:.6g}"
    if isinstance(v, (dict, list, tuple)):
        return json.dumps(v, default=str, ensure_ascii=False)
    return v


def tex_escape(s: Any) -> str:
    return (str(s).replace("\\", r"\textbackslash{}").replace("&", r"\&").replace("%", r"\%")
            .replace("_", r"\_").replace("#", r"\#").replace("$", r"\$"))


def fmt(v: Any, kind: str = "auto") -> str:
    if v is None or (isinstance(v, float) and v != v):
        return "--"
    if kind == "pct":
        return f"{100 * float(v):.1f}"
    if kind == "int":
        return f"{int(round(float(v)))}"
    if kind == "usd":
        return f"{float(v):.2f}"
    if kind == "k":
        return f"{float(v) / 1000:.1f}K"
    if isinstance(v, float):
        return f"{v:.2f}"
    return tex_escape(v)


def write_tex_table(path: Path, header: Sequence[str], rows: Sequence[Sequence[str]], *, align: str | None = None,
                    note: str | None = None) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    align = align or ("l" + "r" * (len(header) - 1))
    lines = [f"% generated by eval — do not edit by hand ({path.name})",
             f"\\begin{{tabular}}{{{align}}}", "\\toprule",
             " & ".join(f"\\textbf{{{tex_escape(h)}}}" for h in header) + " \\\\", "\\midrule"]
    for r in rows:
        lines.append(" & ".join(str(c) for c in r) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    if note:
        lines.append(f"% {note}")
    path.write_text("\n".join(lines) + "\n")
    return path


def bar_png(path: Path, labels: Sequence[str], values: Sequence[float], *, errors: Sequence[tuple[float, float]] | None = None,
            ylabel: str = "", title: str = "", ylim: tuple[float, float] | None = None) -> Path | None:
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except Exception:
        return None
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(figsize=(max(4, 1.1 * len(labels) + 1), 3.2), dpi=160)
    x = list(range(len(labels)))
    yerr = None
    if errors:
        yerr = [[max(0.0, v - lo) for v, (lo, _) in zip(values, errors)], [max(0.0, hi - v) for v, (_, hi) in zip(values, errors)]]
    ax.bar(x, values, yerr=yerr, capsize=3, color="#4C72B0", edgecolor="black", linewidth=0.5)
    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=20, ha="right")
    ax.set_ylabel(ylabel)
    if title:
        ax.set_title(title, fontsize=10)
    if ylim:
        ax.set_ylim(*ylim)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)
    return path


def lines_png(path: Path, x: Sequence[float], series: dict[str, Sequence[float]], *, xlabel: str = "", ylabel: str = "",
              title: str = "", errors: dict[str, Sequence[tuple[float, float]]] | None = None) -> Path | None:
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except Exception:
        return None
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(figsize=(5, 3.2), dpi=160)
    for name, ys in series.items():
        ax.plot(x, ys, marker="o", label=name)
        if errors and name in errors:
            lo = [e[0] for e in errors[name]]
            hi = [e[1] for e in errors[name]]
            ax.fill_between(x, lo, hi, alpha=0.15)
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    if title:
        ax.set_title(title, fontsize=10)
    ax.legend(frameon=False, fontsize=8)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)
    return path


def scatter_png(path: Path, points: dict[str, tuple[float, float]], *, xlabel: str, ylabel: str, title: str = "",
                xerr: dict[str, tuple[float, float]] | None = None, yerr: dict[str, tuple[float, float]] | None = None) -> Path | None:
    """Accuracy–cost plane: one labelled point per arm."""
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except Exception:
        return None
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(figsize=(4.8, 3.6), dpi=160)
    for name, (xv, yv) in points.items():
        xe = [[xv - xerr[name][0]], [xerr[name][1] - xv]] if xerr and name in xerr else None
        ye = [[yv - yerr[name][0]], [yerr[name][1] - yv]] if yerr and name in yerr else None
        ax.errorbar([xv], [yv], xerr=xe, yerr=ye, fmt="o", capsize=3)
        ax.annotate(name, (xv, yv), textcoords="offset points", xytext=(5, 5), fontsize=8)
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    if title:
        ax.set_title(title, fontsize=10)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)
    return path
