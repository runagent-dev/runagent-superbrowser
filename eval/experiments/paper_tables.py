"""Generate the paper's results tables and every prose number from frozen records.

    python -m eval.experiments.paper_tables --freeze   # copy analyzer/audit outputs into eval/artifacts/ablate10_paper/
    python -m eval.experiments.paper_tables            # write ../paper/tables/{tab_arms,tab_paired,tab_bylevel,tab_csd,tab_sensitivity,numbers}.tex
    python -m eval.experiments.paper_tables --check    # regenerate into a temp dir and diff against the paper (the golden test)

Everything is computed from ONE file, ``eval/artifacts/ablate10_paper/results.jsonl``
(the per-run records with the analyzers' process metrics), plus the
pre-registered ``exclusions.json``, the sweep audit (``audit.json``) and the
model-split per-run table. No number in §7/§8 is typed by hand: the prose cites
the ``\\Num...`` macros written to ``numbers.tex``, and ``--check`` fails when a
committed table or macro differs from what the records say.

Conventions: primary tables use the pre-registered task exclusions
(``analysis.split_pre_registered``); the all-task numbers appear only in the
sensitivity table. The two confirmatory comparisons (E2: Ledger vs FIFO, Ledger
vs full history) are reported unadjusted; the five secondary comparisons share
one Holm family.
"""
