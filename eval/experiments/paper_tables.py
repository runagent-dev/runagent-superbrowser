# ------------------------------------------------------------------ formatting
def pct(x: float | None, nd: int = 0) -> str:
    return "--" if x is None else f"{100 * x:.{nd}f}"


def signed_pp(x: float) -> str:
    v = 100 * x
    return f"{v:+.1f}".replace("+", "+")


def comma(n: float | None) -> str:
    return "--" if n is None else f"{int(round(n)):,}".replace(",", "{,}")


def kilo(n: float | None) -> str:
    return "--" if n is None else f"{n / 1000:.1f}K"


def pval(p: float | None) -> str:
    if p is None or (isinstance(p, float) and math.isnan(p)):
        return "--"
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def dec(x: float | None, nd: int = 3) -> str:
    return "--" if x is None else f"{x:.{nd}f}"


def ci_pp(lo: float, hi: float) -> str:
    return f"[{100 * lo:+.1f}, {100 * hi:+.1f}]"


# ---------------------------------------------------------------------- inputs
def load_inputs(frozen: Path) -> dict[str, Any]:
    recs = read_results(frozen / "results.jsonl")
    if not recs:
        raise SystemExit(f"no records in {frozen / 'results.jsonl'} — run --freeze first")
    audit = json.loads((frozen / "audit.json").read_text(encoding="utf-8")) if (frozen / "audit.json").exists() else {}
    ms = list(csv.DictReader((frozen / "modelsplit__per_run.csv").open(encoding="utf-8"))) if (frozen / "modelsplit__per_run.csv").exists() else []
    return {"records": recs, "audit": audit, "modelsplit": ms}


def compute(inputs: dict[str, Any]) -> dict[str, Any]:
    all_recs: list[RunRecord] = inputs["records"]
    primary, dropped = analysis.split_pre_registered(all_recs)
    arms_p = analysis.by_arm(primary)
    arms_a = analysis.by_arm(all_recs)
    summ = analysis.arm_summary(primary, apply_exclusions=False)
    summ_all = analysis.arm_summary(all_recs, apply_exclusions=False)
    pairs: dict[str, dict[str, Any]] = {}
    pairs_all: dict[str, dict[str, Any]] = {}
    for row in PAIR_ROWS:
        if row is None:
            continue
        _, arm, _, conf = row
        pb = analysis.paired_binary(arms_p, "ledger", arm)
        pb["confirmatory"] = conf
        pairs[arm] = pb
        pairs_all[arm] = analysis.paired_binary(arms_a, "ledger", arm)
    secondary = [a for r in PAIR_ROWS if r for a in [r[1]] if not r[3]]
    for arm, adj in zip(secondary, stats.holm([pairs[a]["p_value"] for a in secondary])):
        pairs[arm]["p_holm"] = adj
    for arm in pairs:
        pairs[arm].setdefault("p_holm", None)
    # paired continuous diagnostics
    pm: dict[str, dict[str, Any]] = {}
    for name, getter in (("prompt_peak", analysis.METRIC_GETTERS["prompt_peak"]),
                         ("first_path", analysis.METRIC_GETTERS["first_path_success"]),
                         ("csd", analysis.METRIC_GETTERS["csd_observed"]),
                         ("vision_calls", analysis.METRIC_GETTERS["vision_calls"]),
                         ("tool_calls", analysis.METRIC_GETTERS["tool_calls"]),
                         ("usd", analysis.METRIC_GETTERS["usd"])):
        for arm in ("full_history", "fifo", "summary", "no_ladder", "fresh_vision"):
            pm[f"{name}:{arm}"] = analysis.paired_metric(arms_p, "ledger", arm, getter, name=name)
    # by level
    bylevel: dict[str, dict[str, tuple[int, int]]] = {}
    level_of = {str(r.ids["task_id"]): str(r.ids.get("level")) for r in primary}
    for arm, runs in arms_p.items():
        bylevel[arm] = {}
        for lv in LEVELS:
            ks = [r for (t, _), r in runs.items() if level_of.get(t) == lv]
            bylevel[arm][lv] = (sum(1 for r in ks if r.outcome.get("success")), len(ks))
    level_counts = Counter(level_of.values())
    level_counts_all = Counter(str(r.ids.get("level")) for r in all_recs if str(r.ids.get("arm")) == "ledger")
    # failure classes
    fail: dict[str, dict[str, int]] = {}
    for arm, runs in arms_p.items():
        rs = [r for r in runs.values() if not r.outcome.get("success")]
        fail[arm] = {"failures": len(rs), "premature_done": sum(1 for r in rs if r.outcome.get("failure_reason") == "premature_done")}
    # sweep cost / time over ALL records (the money was spent)
    usd = sum(float((r.cost or {}).get("usd") or 0) for r in all_recs)
    usd_judge = sum(float((r.cost or {}).get("usd_judge") or 0) for r in all_recs)
    wall_h = sum(float(r.timing.get("wall_s") or 0) for r in all_recs) / 3600
    # model split
    ms = inputs["modelsplit"]
    ms_fixed = [r for r in ms if r.get("task_id") == "petfinder_rabbits"]
    ms_models = sorted({r["arm"] for r in ms_fixed})
    ms_done = [r for r in ms_fixed if str(r.get("success")).lower() == "true"]
    ms_failed = sorted(r["arm"] for r in ms_fixed if str(r.get("success")).lower() != "true")
    ms_tools = [int(float(r["tool_calls"])) for r in ms_fixed if r.get("tool_calls")]
    return {"primary": primary, "all": all_recs, "dropped": dropped, "summ": summ, "summ_all": summ_all,
            "pairs": pairs, "pairs_all": pairs_all, "pm": pm, "bylevel": bylevel, "level_counts": level_counts,
            "level_counts_all": level_counts_all, "fail": fail,
            "cost": {"agent": usd, "judge": usd_judge, "total": usd + usd_judge, "wall_h": wall_h,
                     "per_run_all": (usd + usd_judge) / len(all_recs)},
            "modelsplit": {"models": ms_models, "completed": len(ms_done), "failed": ms_failed,
                           "tools_min": min(ms_tools) if ms_tools else None, "tools_max": max(ms_tools) if ms_tools else None},
            "audit": inputs["audit"]}


# ---------------------------------------------------------------------- tables
def _row(label: str, bold: bool, cells: list[str]) -> str:
    lab = f"\\textbf{{{label}}}" if bold else label
    return " & ".join([lab] + cells) + " \\\\"


def tab_arms(c: dict[str, Any]) -> str:
    n = next(iter(c["summ"].values()))["n"]
    lines = [HEADER, "\\begin{table}[t]",
             f"\\caption{{All eight arms on the same {n} primary tasks (one task excluded under the pre-registered "
             "same-model rule, \\S\\ref{sec:sweep}), one seed, host model \\code{glm-5.3-flash}. TSR is a raw count with a "
             "Wilson 95\\% interval; peak context is the largest prompt of a run in tokens, given as the mean over runs and as "
             "the single largest run of the arm; cost is measured per run (agent and vision calls, judging excluded) and per "
             "successful run. Critical-state durability is in Table~\\ref{tab:csd}. The production system is the first row.}",
             "\\label{tab:arms}", "\\begin{center}\\small\\setlength{\\tabcolsep}{4pt}", "\\begin{tabular}{lccrrrrrrr}", "\\toprule",
             "\\textbf{Arm} & \\textbf{TSR} & \\textbf{95\\% CI} & \\textbf{Iters} & \\textbf{Tools} & \\textbf{Vision} & "
             "\\textbf{Peak ctx} & \\textbf{Max ctx} & \\textbf{\\$/run} & \\textbf{\\$/succ} \\\\", "\\midrule"]
    for row in ARM_ROWS:
        if row is None:
            lines.append("\\midrule")
            continue
        arm, label, bold = row
        s = c["summ"][arm]
        lo, hi = s["wilson"]
        lines.append(_row(label, bold, [f"{s['k']}/{s['n']} ({pct(s['tsr'])}\\%)", f"[{pct(lo)}, {pct(hi)}]",
                                        f"{s['iterations']:.1f}", f"{s['tool_calls']:.1f}", f"{s['vision_calls']:.1f}",
                                        kilo(s["prompt_peak"]), kilo(s["prompt_peak_max"]),
                                        f"{s['usd']:.3f}", dec(s["usd_per_success"], 3)]))
    lines += ["\\bottomrule\\end{tabular}\\end{center}\\end{table}"]
    return "\n".join(lines) + "\n"


def tab_csd(c: dict[str, Any]) -> str:
    lines = [HEADER, "\\begin{table}[t]",
             "\\caption{Critical-state durability, event-pooled. \\emph{Observation-derived} items are values first seen in a tool "
             "result and reused later in an action argument or the final answer; \\emph{task-given} items are the values named in "
             "the instruction, checked at the last iteration. Lost/scored counts are summed over the runs of an arm that produced "
             "at least one scored event (\\emph{runs}); the pooled rate is items present over items scored. The per-run macro-average "
             "of earlier drafts is given for comparison: it weights every run equally regardless of how many items it carried, "
             "which is what made the Ledger appear to lead.}",
             "\\label{tab:csd}", "\\begin{center}\\small\\setlength{\\tabcolsep}{4pt}", "\\begin{tabular}{lrrrrrr}", "\\toprule",
             "\\textbf{Arm} & \\multicolumn{3}{c}{\\textbf{Observation-derived}} & \\multicolumn{2}{c}{\\textbf{Task-given}} & \\textbf{Macro} \\\\",
             "\\cmidrule(lr){2-4}\\cmidrule(lr){5-6}",
             " & \\textbf{lost/scored} & \\textbf{pooled CSD} & \\textbf{runs} & \\textbf{lost/scored} & \\textbf{pooled} & \\textbf{mean} \\\\", "\\midrule"]
    for row in ARM_ROWS:
        if row is None:
            lines.append("\\midrule")
            continue
        arm, label, bold = row
        s = c["summ"][arm]
        lines.append(_row(label, bold, [f"{s['csd_lost']}/{s['csd_events']}", dec(s["csd_observed_pooled"]), str(s["csd_n_runs"]),
                                        f"{s['csd_task_given_lost']}/{s['csd_task_given_events']}", dec(s["csd_task_given_pooled"]),
                                        dec(s["csd_observed"])]))
    lines += ["\\bottomrule\\end{tabular}\\end{center}\\end{table}"]
    return "\n".join(lines) + "\n"


def tab_paired(c: dict[str, Any]) -> str:
    n = next(iter(c["pairs"].values()))["n"]
    nsec = sum(1 for r in PAIR_ROWS if r and not r[3])
    lines = [HEADER, "\\begin{table}[t]",
             f"\\caption{{Paired comparisons of the Ledger against each ablation on identical task ids ($n{{=}}{n}$). $\\Delta$ is "
             "Ledger minus ablation in success-rate points with a paired bootstrap 95\\% interval; discordant pairs count tasks only "
             "one arm solved; $p$ is the exact McNemar test. Negative $\\Delta$ means the ablation did better. The first two rows "
             "($\\dagger$) are the pre-registered confirmatory comparisons and are reported unadjusted; the remaining "
             f"{nsec} are secondary and share one Holm step-down family ($p_{{\\mathrm{{Holm}}}}$).}}",
             "\\label{tab:paired}", "\\begin{center}\\small", "\\begin{tabular}{llrrcrr}", "\\toprule",
             "\\textbf{Study} & \\textbf{Ledger vs.} & \\textbf{$\\Delta$ (pp)} & \\textbf{95\\% CI} & \\textbf{Discordant (L / abl.)} & \\textbf{$p$} & \\textbf{$p_{\\mathrm{Holm}}$} \\\\",
             "\\midrule"]
    for row in PAIR_ROWS:
        if row is None:
            lines.append("\\midrule")
            continue
        study, arm, label, conf = row
        pb = c["pairs"][arm]
        p = pval(pb["p_value"])
        if pb["p_value"] < 0.05:
            p = f"\\textbf{{{p}}}"
        dag = "$^\\dagger$" if conf else ""
        holm_s = pval(pb["p_holm"]) if pb["p_holm"] is not None else "--"
        cells = [f"{study}{dag}", label, signed_pp(pb["diff"]), ci_pp(pb["diff_ci_low"], pb["diff_ci_high"]),
                 f"{pb['a_only']} / {pb['b_only']}", p, holm_s]
        lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\bottomrule\\end{tabular}\\end{center}\\end{table}"]
    return "\n".join(lines) + "\n"


def tab_bylevel(c: dict[str, Any]) -> str:
    lc = c["level_counts"]
    lines = [HEADER, "\\begin{table}[t]",
             f"\\caption{{Success by benchmark difficulty level ({lc['easy']} easy / {lc['medium']} medium / {lc['hard']} hard "
             "among the primary tasks). The Ledger does not lead at any level.}",
             "\\label{tab:bylevel}", "\\begin{center}\\small", "\\begin{tabular}{lccc}", "\\toprule",
             "\\textbf{Arm} & \\textbf{Easy} & \\textbf{Medium} & \\textbf{Hard} \\\\", "\\midrule"]
    for row in ARM_ROWS:
        if row is None:
            lines.append("\\midrule")
            continue
        arm, label, bold = row
        b = c["bylevel"][arm]
        lines.append(_row(label, bold, [f"{b[lv][0]}/{b[lv][1]}" for lv in LEVELS]))
    lines += ["\\bottomrule\\end{tabular}\\end{center}\\end{table}"]
    return "\n".join(lines) + "\n"


def tab_sensitivity(c: dict[str, Any]) -> str:
    n_all = next(iter(c["summ_all"].values()))["n"]
    n = next(iter(c["summ"].values()))["n"]
    lines = [HEADER, "\\begin{table}[t]",
             f"\\caption{{Sensitivity to the one pre-registered exclusion: success counts and paired differences against the Ledger "
             f"with the excluded task restored ($n{{=}}{n_all}$) beside the primary analysis ($n{{=}}{n}$). Every arm failed the "
             "excluded task, so numerators, discordant pairs and exact McNemar $p$-values are identical; only denominators move.}",
             "\\label{tab:sensitivity}", "\\begin{center}\\small", "\\begin{tabular}{lcccc}", "\\toprule",
             f"\\textbf{{Arm}} & \\textbf{{TSR ($n{{=}}{n}$)}} & \\textbf{{TSR ($n{{=}}{n_all}$)}} & \\textbf{{$\\Delta$ vs Ledger ($n{{=}}{n}$)}} & \\textbf{{$\\Delta$ ($n{{=}}{n_all}$)}} \\\\",
             "\\midrule"]
    for row in ARM_ROWS:
        if row is None:
            lines.append("\\midrule")
            continue
        arm, label, bold = row
        s, sa = c["summ"][arm], c["summ_all"][arm]
        if arm == "ledger":
            d1 = d2 = "--"
        else:
            d1, d2 = signed_pp(c["pairs"][arm]["diff"]), signed_pp(c["pairs_all"][arm]["diff"])
        lines.append(_row(label, bold, [f"{s['k']}/{s['n']} ({pct(s['tsr'])}\\%)", f"{sa['k']}/{sa['n']} ({pct(sa['tsr'])}\\%)", d1, d2]))
    lines += ["\\bottomrule\\end{tabular}\\end{center}\\end{table}"]
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------- numbers
def numbers(c: dict[str, Any]) -> str:
    m: dict[str, str] = {}
    S, P, PM, A = c["summ"], c["pairs"], c["pm"], c["audit"]
    n = next(iter(S.values()))["n"]
    n_all = next(iter(c["summ_all"].values()))["n"]
    m["Tasks"] = str(n)
    m["TasksAll"] = str(n_all)
    m["Arms"] = str(len(S))
    m["Runs"] = str(len(c["all"]))
    m["RunsPrimary"] = str(len(c["primary"]))
    m["ExcludedTasks"] = str(len(c["dropped"]))
    for lv in LEVELS:
        m[f"{lv.capitalize()}Tasks"] = str(c["level_counts"].get(lv, 0))
        m[f"{lv.capitalize()}TasksAll"] = str(c["level_counts_all"].get(lv, 0))
    for arm, key in MACRO_ARM.items():
        s = S[arm]
        m[f"Tsr{key}"] = f"{s['k']}/{s['n']}"
        m[f"TsrPct{key}"] = pct(s["tsr"])
        m[f"Succ{key}"] = str(s["k"])
        m[f"Iters{key}"] = f"{s['iterations']:.1f}"
        m[f"Tools{key}"] = f"{s['tool_calls']:.1f}"
        m[f"Vision{key}"] = f"{s['vision_calls']:.1f}"
        m[f"PeakMean{key}"] = kilo(s["prompt_peak"])
        m[f"PeakMax{key}"] = comma(s["prompt_peak_max"])
        m[f"PeakMaxPct{key}"] = f"{100 * s['prompt_peak_max'] / CONTEXT_WINDOW:.0f}"
        m[f"Usd{key}"] = f"{s['usd']:.3f}"
        m[f"UsdPerSucc{key}"] = dec(s["usd_per_success"], 3)
        m[f"CsdPooled{key}"] = dec(s["csd_observed_pooled"])
        m[f"CsdLost{key}"] = str(s["csd_lost"])
        m[f"CsdEvents{key}"] = str(s["csd_events"])
        m[f"CsdRuns{key}"] = str(s["csd_n_runs"])
        m[f"CsdMacro{key}"] = dec(s["csd_observed"])
        m[f"CsdTgLost{key}"] = str(s["csd_task_given_lost"])
        m[f"CsdTgEvents{key}"] = str(s["csd_task_given_events"])
        m[f"FirstPath{key}"] = dec(s["first_path_success"], 2)
        m[f"FirstPathRuns{key}"] = str(s["first_path_n_runs"])
        m[f"Failures{key}"] = str(c["fail"][arm]["failures"])
        m[f"Premature{key}"] = str(c["fail"][arm]["premature_done"])
        if arm != "ledger":
            pb = P[arm]
            m[f"Delta{key}"] = signed_pp(pb["diff"])
            m[f"DeltaAbs{key}"] = f"{abs(100 * pb['diff']):.1f}"
            m[f"CiLo{key}"] = f"{100 * pb['diff_ci_low']:+.1f}"
            m[f"CiHi{key}"] = f"{100 * pb['diff_ci_high']:+.1f}"
            m[f"Disc{key}"] = f"{pb['a_only']} / {pb['b_only']}"
            m[f"DiscL{key}"] = str(pb["a_only"])
            m[f"DiscA{key}"] = str(pb["b_only"])
            m[f"P{key}"] = pval(pb["p_value"])
            m[f"PHolm{key}"] = pval(pb["p_holm"]) if pb["p_holm"] is not None else "--"
    # secondary p range
    sec = [P[r[1]]["p_value"] for r in PAIR_ROWS if r and not r[3]]
    conf = [P[r[1]]["p_value"] for r in PAIR_ROWS if r and r[3]]
    m["PMemoryMin"] = pval(min(conf + [P["summary"]["p_value"]]))
    m["PMemoryMax"] = pval(max(conf + [P["summary"]["p_value"]]))
    m["SecondaryTests"] = str(len(sec))
    m["DiscordantFh"] = str(P["full_history"]["a_only"] + P["full_history"]["b_only"])
    # paired continuous
    pk = PM["prompt_peak:full_history"]
    m["PeakDiffFh"] = comma(pk["mean_diff"])
    m["PeakDiffFhCiLo"] = comma(pk["ci"][0]) if "ci" in pk else comma(pk.get("ci_low"))
    m["PeakDiffFhCiHi"] = comma(pk["ci"][1]) if "ci" in pk else comma(pk.get("ci_high"))
    m["PeakDiffFhP"] = pval(pk.get("wilcoxon_p"))
    m["PeakDiffFhN"] = str(pk["n"])
    fp = PM["first_path:full_history"]
    m["FirstPathDiffFh"] = f"{fp['mean_diff']:+.2f}"
    m["FirstPathDiffFhCiLo"] = f"{(fp['ci'][0] if 'ci' in fp else fp.get('ci_low')):+.2f}"
    m["FirstPathDiffFhCiHi"] = f"{(fp['ci'][1] if 'ci' in fp else fp.get('ci_high')):+.2f}"
    m["FirstPathDiffFhP"] = pval(fp.get("wilcoxon_p"))
    m["FirstPathDiffFhN"] = str(fp["n"])
    cs = PM["csd:full_history"]
    m["CsdPairedNFh"] = str(cs["n"])
    m["CsdPairedDiffFh"] = f"{cs['mean_diff']:+.3f}"
    m["CsdPairedPFh"] = pval(cs.get("wilcoxon_p"))
    vc = PM["vision_calls:fresh_vision"]
    m["VisionDiffFreshVision"] = f"{vc['mean_diff']:.1f}"
    m["VisionDiffFreshVisionP"] = pval(vc.get("wilcoxon_p"))
    m["VisionRatio"] = f"{S['ledger']['vision_calls'] / S['fresh_vision']['vision_calls']:.1f}"
    tc = PM["tool_calls:no_ladder"]
    m["ToolDiffNoLadder"] = f"{tc['mean_diff']:+.1f}"
    m["ToolDiffNoLadderP"] = pval(tc.get("wilcoxon_p"))
    # context
    m["ContextWindow"] = comma(CONTEXT_WINDOW)
    m["PeakMaxOverall"] = comma(max(s["prompt_peak_max"] for s in S.values()))
    m["PeakMaxOverallPct"] = f"{100 * max(s['prompt_peak_max'] for s in S.values()) / CONTEXT_WINDOW:.0f}"
    m["CtxEstMaxOverall"] = comma(max(s["ctx_peak_max"] for s in S.values()))
    m["RunsOverSnip"] = str(sum(s["n_over_snip_threshold"] for s in S.values()))
    m["SnipThreshold"] = comma(CONTEXT_WINDOW - 16_384 - 1024)
    m["ArmsWithinFactorThree"] = str(sum(1 for s in S.values() if CONTEXT_WINDOW / s["prompt_peak_max"] < 3))
    # cost / time
    C = c["cost"]
    m["CostTotal"] = f"{C['total']:.2f}"
    m["CostAgent"] = f"{C['agent']:.2f}"
    m["CostJudge"] = f"{C['judge']:.2f}"
    m["CostPerRunAll"] = f"{C['per_run_all']:.2f}"
    m["SummedRunHours"] = f"{C['wall_h']:.0f}"
    # audit-derived provenance
    if A:
        cd, ie, ts, ji = A.get("code_drift", {}), A.get("infra_errors", {}), A.get("toolset", {}), A.get("judge_input", {})
        m["Shas"] = str(cd.get("n_shas", "--"))
