def generate(frozen: Path, out_dir: Path) -> dict[str, str]:
    c = compute(load_inputs(frozen))
    files = {"tab_arms.tex": tab_arms(c), "tab_csd.tex": tab_csd(c), "tab_paired.tex": tab_paired(c),
             "tab_bylevel.tex": tab_bylevel(c), "tab_sensitivity.tex": tab_sensitivity(c), "numbers.tex": numbers(c)}
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (out_dir / name).write_text(text, encoding="utf-8")
    return files


def freeze(frozen: Path, artifacts: Path) -> list[str]:
    """Copy the analyzer / audit outputs behind the paper into the frozen dir."""
    frozen.mkdir(parents=True, exist_ok=True)
    copied = []
    plan = [("e2_memory_policy", "", ("arm_summary.csv", "arm_summary.json", "arm_summary_all_tasks.csv", "paired_binary.json",
                                     "paired_metrics.csv", "per_run.csv", "memory_table.csv"))]
    for e in ("e4_deadend", "e5_perception_reuse", "e7_click_cascade", "e8_topology"):
        plan.append((e, f"{e}__", ("arm_summary.csv", "paired_binary.json", "paired_metrics.csv")))
    plan.append(("e7_click_cascade", "e7_click_cascade__", ("execution_table.csv",)))
    plan.append(("e4_deadend", "e4_deadend__", ("deadend_table.csv",)))
    plan.append(("e5_perception_reuse", "e5_perception_reuse__", ("churn_strata.csv",)))
    plan.append((f"{EXPERIMENT}_audit", "", ("audit.json", "audit.md")))
    plan.append(("modelsplit_replay", "modelsplit__", ("per_run.csv",)))
    plan.append(("e11_cost", "e11_cost__", ("cost_by_arm.csv", "price_table_used.json")))
    plan.append(("e12_traces", "e12_traces__", (f"{EXPERIMENT}__ledger_vs_full_history.md",)))
    for src_dir, prefix, names in plan:
        for name in names:
            src = artifacts / src_dir / name
            if src.exists():
                shutil.copyfile(src, frozen / f"{prefix}{name}")
                copied.append(f"{prefix}{name}")
    return copied


def check(frozen: Path, paper_tables: Path) -> list[str]:
    """Regenerate into a temp dir; return the names that differ from the committed
    copy (the paper's tables/ dir, or the golden copy under the frozen dir)."""
    with tempfile.TemporaryDirectory() as td:
        files = generate(frozen, Path(td))
        diffs = []
        for name in files:
            committed = paper_tables / name
            if not committed.exists() or committed.read_text(encoding="utf-8") != files[name]:
                diffs.append(name)
        return diffs


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Paper tables + prose-number macros from frozen records")
    ap.add_argument("--frozen", default=str(FROZEN))
    ap.add_argument("--paper-tables", default=str(PAPER_DIR / "tables"))
    ap.add_argument("--artifacts", default=str(REPO_ROOT / "eval" / "artifacts"))
    ap.add_argument("--freeze", action="store_true", help="copy analyzer/audit outputs into the frozen dir first")
    ap.add_argument("--check", action="store_true", help="golden check: fail if the paper's tables differ from the records")
    args = ap.parse_args(argv)
    frozen = Path(args.frozen)
    if args.freeze:
        copied = freeze(frozen, Path(args.artifacts))
        print(f"froze {len(copied)} file(s) into {frozen}: " + ", ".join(copied))
    if args.check:
        diffs = check(frozen, Path(args.paper_tables))
        if diffs:
            print("STALE: " + ", ".join(diffs) + f" — regenerate with `python -m eval.experiments.paper_tables`")
            return 1
        print("paper tables match the frozen records")
        return 0
    files = generate(frozen, Path(args.paper_tables))
    generate(frozen, frozen / "tables")          # tracked golden copy inside the repo
    print(f"wrote {', '.join(files)} -> {args.paper_tables} (golden copy in {frozen / 'tables'})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
